/// What [SyncPendingVotes] needs: what the session guard needs, the outbox, the
/// server that records votes, and the number of attempts after which a vote is
/// given up.
abstract interface class SyncPendingVotesDeps implements RequireSessionDeps {
  /// The local queue of votes.
  VoteOutbox get outbox;

  /// The server that records votes.
  VoteRepository get votes;

  /// Configuration, set once by the composition root: after this many
  /// unexpected failures a vote is given up (rejected as `voteUndeliverable`)
  /// instead of being retried for ever.
  int get maxAttempts;
}

/// How a run of [SyncPendingVotes] ended.
enum SyncOutcome implements StableValue {
  /// The whole queue was gone through. Votes that failed unexpectedly may
  /// remain, to be retried.
  completed('completed'),

  /// The run stopped early on a condition that concerns every vote; the rest is
  /// still pending.
  interrupted('interrupted'),

  /// Another run of the same use case was in progress: nothing was done.
  alreadyRunning('alreadyRunning');

  new(this.value);

  @override
  final String value;
}

/// What stops a whole run: the network or the session is gone, or the outbox
/// cannot be written. The members are [NetworkUnavailableError],
/// [UnauthorizedError], [StorageWriteFailedError], a `SessionRequiredError` and
/// a [SessionChangedError].
typedef SyncInterruption = AppError;

/// A vote that the server refused, as a run reports it: which resolution, and
/// why. Never the choice.
@freezed
abstract class RejectedSync with _$RejectedSync {
  /// Creates the report of a rejected vote.
  const factory({
    /// The resolution the vote was on.
    required ResolutionId resolutionId,

    /// Why the vote will not be sent.
    required RejectionReason reason,
  }) = _RejectedSync;
}

/// What a run did. It names resolutions and reasons only: the choice of a vote
/// is a secret ballot, and a report is built to be shown, logged and passed
/// around. The votes themselves stay in the outbox, where they are read by the
/// voter they belong to.
abstract interface class SyncProgress {
  /// The resolutions of the votes the server recorded; they have left the
  /// outbox.
  List<ResolutionId> get synced;

  /// The votes moved to the rejected state during this run; they stay in the
  /// outbox.
  List<RejectedSync> get rejected;

  /// The pending votes of the user still in the outbox, counted after the run.
  int get remaining;
}

/// What [SyncPendingVotes] answers: one of [SyncAlreadyRunning],
/// [SyncCompleted] and [SyncInterrupted]. [outcome] gives it as a stable value.
///
/// It is generated by `freezed` so that its text prints every field: a field
/// added to a report cannot go unseen by the tests that search the text of a
/// report for a vote choice.
@freezed
sealed class SyncReport with _$SyncReport {
  /// Another run was in progress on this instance: nothing was done.
  const factory alreadyRunning() = SyncAlreadyRunning;

  /// The whole queue was gone through. Votes that failed unexpectedly may
  /// remain, to be retried.
  @Implements<SyncProgress>()
  const factory completed({
    required List<ResolutionId> synced,
    required List<RejectedSync> rejected,
    required int remaining,
  }) = SyncCompleted;

  /// The run stopped early on a condition that concerns every vote; the rest is
  /// still pending.
  @Implements<SyncProgress>()
  const factory interrupted({
    required List<ResolutionId> synced,
    required List<RejectedSync> rejected,
    required int remaining,

    /// What stopped the run.
    required SyncInterruption interruptedBy,
  }) = SyncInterrupted;

  const new _();

  /// How the run ended.
  SyncOutcome get outcome => switch (this) {
    SyncAlreadyRunning() => SyncOutcome.alreadyRunning,
    SyncCompleted() => SyncOutcome.completed,
    SyncInterrupted() => SyncOutcome.interrupted,
  };
}

/// What fails the whole call, before any vote is sent: no valid session, or an
/// outbox that cannot be read. The members are a `SessionRequiredError` and a
/// [StorageReadFailedError].
typedef SyncPendingVotesError = AppError;

/// What became of one pending vote.
sealed class _Settlement {
  const new();
}

/// The server recorded the vote, and it left the outbox.
final class _Synced extends _Settlement {
  const new();
}

/// The vote was moved to the rejected state.
final class _Rejected extends _Settlement {
  const new(this.rejected);

  final RejectedSync rejected;
}

/// The vote failed in a way that says nothing about it: it stays pending, the
/// run goes on.
final class _Deferred extends _Settlement {
  const new();
}

/// The vote hit a condition that concerns every vote: the run stops.
final class _Interrupted extends _Settlement {
  const new(this.cause);

  final SyncInterruption cause;
}

/// Sends the votes of the signed-in user that wait in the outbox, oldest first,
/// one at a time. A rejected vote is never sent again.
///
/// - Recorded by the server: removed from the outbox, reported in `synced`, and
///   recorded on the cached copy of its meeting (`recordVoteInCache`).
/// - Rejected for a business reason (closed, already voted, ...): sending it
///   again would change nothing, so it is moved to the rejected state, with its
///   reason, and reported in `rejected`. It stays in the outbox until the user
///   acknowledges it (`AcknowledgeRejectedVote`).
/// - `unexpected`: the server failed in a way that says nothing about the vote.
///   The failure is captured, an attempt is counted on the vote, and the run
///   goes on with the next one. After `maxAttempts` attempts the vote is moved
///   to the rejected state with the reason `voteUndeliverable`, so that the
///   user sees it and one bad vote cannot block the others for ever.
/// - `networkUnavailable` and `unauthorized` concern every vote, not this one:
///   the run stops at once and the vote and the ones after it stay pending. No
///   attempt is counted, so being offline never makes a vote undeliverable.
///   `unauthorized` is the server no longer accepting the session: it also ends
///   the session on the device (see `endRefusedSession`), the votes staying in
///   the outbox for the next time their voter signs in.
/// - The session is checked again before each vote. If nobody is signed in any
///   more, or somebody else is, the run stops: the votes of a user are never
///   sent under another session. (The adapter backs this up: it answers
///   `unauthorized` to a vote whose voter is not the authenticated user.)
/// - A write to the outbox that fails stops the run too, and a vote is reported
///   as settled only once it has really left its pending state.
///
/// - It does not run while the app is locked (`appLocked`, from the session
///   guard), and a run that meets the lock stops there. A vote was confirmed by
///   a biometric prompt when it was cast, but the lock means that nobody has
///   proven they are there since the app started or came back, and a locked app
///   does not talk to the server with the session of its user, nor does it
///   report on their votes. The presentation triggers a run when the app
///   returns to the foreground, and that run follows the unlock. The votes wait
///   in the outbox, and the loss is a delay.
///
/// Only the votes of the signed-in user are read (the port is scoped by voter).
///
/// Who calls it: the presentation or the composition root, when connectivity is
/// regained and when the app returns to the foreground. The application layer
/// does not watch the network.
///
/// What is guaranteed about concurrent calls: while a run is in progress on
/// this instance, another call returns `alreadyRunning` immediately and does
/// nothing, so one instance never sends the same vote twice at once. The guard
/// is an instance field, set before the first `await`: the composition root
/// must therefore share one instance. It does not protect two instances or two
/// processes (a background task next to the app). There the idempotency key
/// keeps a double send harmless: the server records the vote once.
final class SyncPendingVotes {
  /// Creates the use case over [_deps].
  new(this._deps);

  final SyncPendingVotesDeps _deps;
  bool _running = false;

  /// Sends the pending votes of the signed-in user.
  Future<Result<SyncReport, SyncPendingVotesError>> execute() async {
    if (_running) {
      return ok(const SyncAlreadyRunning());
    }

    _running = true;
    try {
      return await _run();
    } finally {
      _running = false;
    }
  }

  Future<Result<SyncReport, SyncPendingVotesError>> _run() async {
    final SyncPendingVotesDeps(:outbox, :monitoring) = _deps;

    final Session session;
    switch (await requireSession(_deps)) {
      case Err(:final error):
        return err(error);
      case Ok(:final value):
        session = value;
    }
    final voterId = session.user.id;

    final List<PendingVote> queue;
    switch (await outbox.list(voterId)) {
      case Err(:final error):
        return err(error);
      case Ok(:final value):
        queue = value.votes.whereType<PendingVote>().toList();
    }

    final synced = <ResolutionId>[];
    final rejected = <RejectedSync>[];
    SyncInterruption? interruption;

    for (final pending in queue) {
      final stillSignedIn = await _checkSession(voterId);
      if (stillSignedIn case Err(:final error)) {
        interruption = error;
        break;
      }

      final settlement = await _settle(pending);
      if (settlement case _Interrupted(:final cause)) {
        interruption = cause;
        break;
      }
      if (settlement is _Synced) {
        synced.add(pending.vote.resolutionId);
      }
      if (settlement case _Rejected(rejected: final report)) {
        rejected.add(report);
      }
    }

    final remaining = await _countRemaining(
      voterId,
      queue.length - synced.length - rejected.length,
    );
    final attributes = <LogAttribute, Object>{
      LogAttribute.synced: synced.length,
      LogAttribute.rejected: rejected.length,
      LogAttribute.remaining: remaining,
    };

    if (interruption == null) {
      monitoring.log(
        LogLevel.info,
        MonitoringEvent.voteSyncCompleted,
        attributes,
      );
      return ok(
        SyncCompleted(synced: synced, rejected: rejected, remaining: remaining),
      );
    }
    monitoring.log(LogLevel.warn, MonitoringEvent.voteSyncInterrupted, {
      ...attributes,
      LogAttribute.errorCode: interruption.code,
    });
    return ok(
      SyncInterrupted(
        synced: synced,
        rejected: rejected,
        remaining: remaining,
        interruptedBy: interruption,
      ),
    );
  }

  /// Is the user the run started for still the signed-in user?
  Future<Result<void, AppError>> _checkSession(UserId voterId) async {
    switch (await requireSession(_deps)) {
      case Err(:final error):
        return err(error);
      case Ok(:final value):
        if (value.user.id != voterId) {
          return err(sessionChanged());
        }
        return ok<void>(null);
    }
  }

  /// The pending votes still in the outbox, read again after the run since the
  /// outbox may have changed while it ran (a vote cast meanwhile, say). If it
  /// cannot be read, the failure is captured and the count falls back on what
  /// the run itself knows.
  Future<int> _countRemaining(UserId voterId, int fallback) async {
    final SyncPendingVotesDeps(:outbox, :monitoring) = _deps;

    switch (await outbox.list(voterId)) {
      case Err(:final error):
        monitoring.captureError(MonitoringEvent.outboxReadFailed, error);
        return fallback;
      case Ok(:final value):
        return value.votes.whereType<PendingVote>().length;
    }
  }

  /// Sends one vote and brings the outbox in line with the answer.
  Future<_Settlement> _settle(PendingVote pending) async {
    switch (await _deps.votes.submit(pending.vote)) {
      case Ok():
        return await _leaveOutbox(pending);
      case Err(:final error):
        if (error is VotingError) {
          return await _reject(pending, error);
        }
        if (error.code == RepositoryErrorCode.unexpected.value) {
          return await _deferOrGiveUp(pending, error);
        }
        if (error.code == RepositoryErrorCode.unauthorized.value) {
          await endRefusedSession(_deps, pending.vote.voterId);
        }
        return _Interrupted(error);
    }
  }

  /// The server has recorded the vote: it must not be sent again, so it leaves
  /// the outbox.
  Future<_Settlement> _leaveOutbox(PendingVote pending) async {
    final removed = await _deps.outbox.remove(pending.vote.idempotencyKey);
    if (removed case Err(:final error)) {
      return _Interrupted(error);
    }

    await recordVoteInCache(_deps, pending.vote);
    return const _Synced();
  }

  /// The vote will never be sent: it moves to the rejected state, and stays
  /// there.
  Future<_Settlement> _reject(
    PendingVote pending,
    RejectionReason reason,
  ) async {
    final SyncPendingVotesDeps(:clock, :outbox, :monitoring) = _deps;
    final rejectedAt = clock.now();

    final moved = await outbox.reject(
      pending.vote.idempotencyKey,
      reason,
      rejectedAt,
    );
    if (moved case Err(:final error)) {
      return _Interrupted(error);
    }

    monitoring.log(LogLevel.warn, MonitoringEvent.voteRejected, {
      LogAttribute.resolutionId: pending.vote.resolutionId,
      LogAttribute.errorCode: reason.code,
      LogAttribute.attempts: pending.attempts,
    });
    return _Rejected(
      RejectedSync(resolutionId: pending.vote.resolutionId, reason: reason),
    );
  }

  /// An unexpected failure: counts an attempt, and gives the vote up once there
  /// are too many.
  Future<_Settlement> _deferOrGiveUp(
    PendingVote pending,
    AppError cause,
  ) async {
    final SyncPendingVotesDeps(:outbox, :monitoring, :maxAttempts) = _deps;
    final attributes = <LogAttribute, Object>{
      LogAttribute.resolutionId: pending.vote.resolutionId,
    };

    monitoring.captureError(
      MonitoringEvent.voteSubmitFailed,
      cause,
      attributes,
    );
    final marked = await outbox.markAttempt(pending.vote.idempotencyKey);
    if (marked case Err(:final error)) {
      monitoring.captureError(
        MonitoringEvent.voteAttemptNotRecorded,
        error,
        attributes,
      );
    }

    final attempted = recordAttempt(pending);
    if (attempted.attempts < maxAttempts) {
      return const _Deferred();
    }
    return await _reject(attempted, voteUndeliverable(attempted.attempts));
  }
}
